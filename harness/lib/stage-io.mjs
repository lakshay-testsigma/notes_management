// What each stage reads, writes, and must reach. `tutor next` prints this so a
// skill never has to guess a path or a target number.

import path from 'node:path';
import { exists } from './io.mjs';
import { CLI } from './root.mjs';
import { openLessonLine, siteUrl } from './topic-store.mjs';
import { stageDefinition } from './stages.mjs';
import { BRIEF_SECTIONS, BRIEF_WORDS } from './validators/brief.mjs';
import { LESSON_WORDS } from './validators/lesson.mjs';
import { FINAL_NOTES_WORDS } from './validators/notes.mjs';
import { digestTarget } from './validators/digest.mjs';
import { repoTarget } from './validators/repo-intel.mjs';

const RUBRICS = {
  sources: 'harness/rubrics/source-quality.md',
  lesson: 'harness/rubrics/lesson-page.md',
  notes: 'harness/rubrics/vault-notes.md',
};

/**
 * Describe one stage for `tutor next`.
 * ctx is the validator context (root, topic, paths, profile, pack, kinds).
 * Returns { inputs, outputs, targets, commands, gate }.
 */
export function describeStage(ctx, stageId) {
  const { root, topic, paths: p, profile } = ctx;
  const id = topic.id;
  const isSkipped = (stage) => ctx.stageStatus(stage) === 'skipped';

  // An input: a file to read, why, and (for the playbook) which heading.
  // `from` names the stage that writes the file; inputs of skipped stages are dropped.
  const input = (file, why, extra = {}) => ({ path: file, why, ...extra });
  const playbook = (section, why) => input(p.playbook, why, { section: `## ${section}` });
  const output = (file, what) => ({ path: file, what });
  const topicJson = (why) => input(p.topic_json, why);
  const safety = playbook('Safety and ethics', 'rules that apply to every stage of this domain');

  const specs = {
    intake: {
      inputs: [
        topicJson('title, depth, and the empty plan to fill'),
        input(p.pack_json, 'subdomains, default stack, and which stages are switched on'),
        playbook('How this domain is learned', 'how to order the ideas and choose prerequisites'),
        safety,
      ],
      outputs: [
        output(p.topic_json, `the plan, written with \`${CLI} plan ${id} --set <file.json>\` (never edit topic.json by hand)`),
        output(p.start_here, 'the topic map; regenerated by the CLI when the plan is set'),
      ],
      targets: {
        plan_fields: ['summary', 'prerequisites', 'outcomes', 'lesson_outline', 'mini_projects', 'digest_targets', 'repo_targets', 'capstone'],
        lesson_pages: profile.lesson_pages,
        mini_projects: profile.mini_projects,
        digests: profile.digests,
        repos: profile.repos,
        capstone: profile.capstone,
      },
    },
    research: {
      inputs: [
        topicJson('the plan: what the sources must cover'),
        playbook('Trusted sources', 'where canonical sources of this domain live'),
        input(RUBRICS.sources, 'the thresholds a source must pass'),
        safety,
      ],
      outputs: [
        output(p.sources_json, `vetted sources, added one by one with \`${CLI} sources ${id} add --file <entry.json>\``),
        output(p.resources, 'the resources note; regenerated by the CLI after every added source'),
      ],
      targets: { sources: profile.sources, tier_a_min: 1 },
    },
    brief: {
      inputs: [
        // The same list as "Inputs" in .claude/skills/learn-brief/SKILL.md, and nothing more.
        topicJson('the plan: summary, prerequisites, outcomes'),
        input(p.sources_json, 'the vetted sources to ground the brief in: tier A first, and those whose use_for has "brief"', { from: 'research' }),
        safety,
        input(p.brief, 'the scaffolded note: keep its frontmatter keys and fill in its body'),
        input(p.concepts_dir, 'file names only, to reuse concept notes that already exist'),
      ],
      outputs: [output(p.brief, 'the brief note')],
      targets: { words: BRIEF_WORDS, sections: BRIEF_SECTIONS.map((s) => `## ${s.heading}`) },
    },
    digest: {
      inputs: [
        topicJson('the plan: digest_targets'),
        input(p.sources_json, 'pick the entries whose use_for includes "digest"', { from: 'research' }),
        input(p.brief, 'the brief, for context', { from: 'brief' }),
        input(RUBRICS.notes, 'the rules for vault notes'),
        safety,
      ],
      outputs: [
        output(`${p.digests_dir}/<source-id>-${topic.slug}.md`, 'one digest note per source, with `sources: [<source-id>]` in the frontmatter'),
        output(p.digests_index, 'the index: a wikilink to every digest note'),
      ],
      targets: { digests: digestTarget(ctx), allowed: profile.digests },
    },
    'repo-intel': {
      inputs: [
        topicJson('the plan: repo_targets'),
        input(p.sources_json, 'pick the entries of type "repo"', { from: 'research' }),
        playbook('Repository analysis focus', 'what to look for in a repository of this domain'),
        input(RUBRICS.notes, 'the rules for vault notes'),
        safety,
      ],
      outputs: [
        output(`${p.repos_cache_dir}/<org>__<repo>/`, 'the shallow clone (never copied into the vault)'),
        output(`${p.repo_intel_dir}/<org>-<repo>/<repo>-overview.md`, 'overview with the commit SHA analyzed; plus <repo>-architecture, <repo>-module-<name>, <repo>-tech-and-services, <repo>-findings, <repo>-takeaways, optional <repo>-pattern-<name>'),
        output(p.repo_intel_index, 'the index: a wikilink to every repository overview'),
        output(`${p.tech_dir}/<Name>.md`, `one note per technology, created with \`${CLI} concept "<Name>" --tech\``),
        output(`${p.concepts_dir}/<Name>.md`, `one note per shared idea, created with \`${CLI} concept "<Name>"\``),
      ],
      targets: {
        repos: repoTarget(ctx),
        allowed: profile.repos,
        slice_budget_tokens: 60000,
        evidence_format: 'path/to/file.ext:line @ <short-sha>',
      },
    },
    lesson: {
      inputs: [
        topicJson('the plan: lesson_outline (one page per entry)'),
        input(p.site_components, 'the exact props of every lesson component'),
        input(p.components_manifest, 'the component names by kind'),
        input(RUBRICS.lesson, 'the rules for a lesson page'),
        playbook('Lesson recipes', 'which component fits which kind of concept'),
        input(p.brief, 'the brief', { from: 'brief' }),
        input(p.digests_index, 'the digests, for facts and examples', { from: 'digest' }),
        input(p.repo_intel_index, 'the repository deep dive, for real examples', { from: 'repo-intel' }),
        safety,
      ],
      outputs: [
        output(`${p.lessons_dir}/NN-<page>.mdx`, 'one lesson page per outline entry (NN = order, two digits)'),
        output(`${p.topic_components_dir}/`, 'topic-specific components, only when a shared one does not fit'),
        output(p.lesson, `the lesson index note: the pages in order and the site path ${siteUrl(topic)}`),
      ],
      targets: {
        open_lesson: openLessonLine(topic),
        pages: profile.lesson_pages,
        words_per_page: LESSON_WORDS,
        per_page: ['at least one visual component', 'at least one activity component', 'no blockquotes, asides, cards, or callouts'],
        across_topic: ['at least one FlowAnimation', 'the final page (highest order in plan.lesson_outline) ends with <Resources />; no other page has it'],
        visual_components: ctx.kinds.visual,
        activity_components: ctx.kinds.activity,
      },
    },
    'mini-projects': {
      inputs: [
        topicJson('the plan: mini_projects'),
        input(p.pack_json, 'default_stack: the language, runtime, and test tool to use'),
        playbook('Mini project patterns', 'what a good mini project looks like in this domain'),
        input(p.brief, 'the brief', { from: 'brief' }),
        input(p.digests_index, 'the digests', { from: 'digest' }),
        safety,
      ],
      outputs: [
        output(`${p.projects_dir}/mini-NN-<name>/`, 'one folder per project with README.md, starter/, solution/'),
        output(p.mini_projects, 'the index note: every project folder name and what it proves'),
      ],
      targets: { mini_projects: profile.mini_projects },
    },
    capstone: {
      inputs: [
        topicJson('the plan: capstone name and problem'),
        input(p.pack_json, 'default_stack and stages.capstone.kind'),
        playbook('Capstone shape', 'what "production ready" means in this domain'),
        input(p.repo_intel_index, 'the repository deep dive: borrow from the takeaways notes', { from: 'repo-intel' }),
        input(p.mini_projects, 'the mini projects, to build on them', { from: 'mini-projects' }),
        safety,
      ],
      outputs: [
        output(`${p.capstone_dir}/`, 'README.md, ARCHITECTURE.md, docs/adr/ (at least one ADR), src/, tests/'),
        output(p.capstone, 'the capstone note: architecture summary and the path of the project'),
      ],
      targets: { required: ['README.md', 'ARCHITECTURE.md', 'docs/adr/*.md', 'src/', 'tests/'], kind: ctx.pack?.stages?.capstone?.kind ?? null },
    },
    notes: {
      inputs: [
        input(p.brief, 'the brief', { from: 'brief' }),
        input(p.lesson, 'the lesson index', { from: 'lesson' }),
        input(p.mini_projects, 'the mini projects index', { from: 'mini-projects' }),
        input(p.digests_index, 'the digests index', { from: 'digest' }),
        input(p.repo_intel_index, 'the repository deep dive index', { from: 'repo-intel' }),
        input(p.capstone, 'the capstone note', { from: 'capstone' }),
        input(p.insights, "the learner's own insights"),
        playbook('Recall focus', 'what is worth remembering in this domain'),
        input(RUBRICS.notes, 'the rules for vault notes'),
        safety,
      ],
      outputs: [
        output(p.final_notes, 'the one-page refresher'),
        output(p.recall, `the recall cards; register them with \`${CLI} recall sync ${id}\``),
      ],
      targets: { final_notes_words: FINAL_NOTES_WORDS, recall_cards_min: profile.recall_cards },
    },
    finalize: {
      inputs: [topicJson('the stage list: every other stage must be done or skipped')],
      outputs: [
        output(p.start_here, 'regenerated topic map'),
        output(p.resources, 'regenerated resources note'),
        output(p.domain_map, 'regenerated domain map'),
        output(p.home, 'regenerated Home'),
      ],
      targets: { all_gates_green: true, site_build_green: true },
    },
  };

  const spec = specs[stageId];
  const inputs = spec.inputs
    .filter((item) => !item.from || !isSkipped(item.from))
    .map((item) => ({ ...item, exists: exists(path.join(root, item.path)) }));

  const commands = {
    start: `${CLI} start ${id} ${stageId}`,
    validate: `${CLI} validate ${id} ${stageId}`,
    done: `${CLI} done ${id} ${stageId}`,
  };
  if (stageId === 'finalize') {
    commands.map = `${CLI} map ${id}`;
    commands.validate = `${CLI} validate ${id} --all`;
    commands.site_build = 'npm run site:build';
  }

  const definition = stageDefinition(stageId);
  return {
    skill: definition.skill,
    skill_file: `.claude/skills/${definition.skill}/SKILL.md`,
    produces: definition.produces,
    inputs,
    outputs: spec.outputs,
    targets: spec.targets,
    gate: commands.validate,
    commands,
  };
}
