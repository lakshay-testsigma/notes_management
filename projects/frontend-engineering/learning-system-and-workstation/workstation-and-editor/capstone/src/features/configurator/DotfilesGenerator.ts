// The single use case: turn a valid DeveloperConfig into a ready dotfiles
// repository — files, an idempotent atomic installer, and a setup checklist.

import {
  DeveloperConfig,
  GeneratedBundle,
  type EditorId,
  type GeneratedFile,
  type ShellId,
} from './model';

const EDITOR_COMMAND: Record<EditorId, string> = {
  vscode: 'code',
  neovim: 'nvim',
  zed: 'zed',
};

export class DotfilesGenerator {
  generate(config: DeveloperConfig): GeneratedBundle {
    const files = this.buildFiles(config);
    const installScript = this.buildInstaller(config, files);
    const checklist = this.buildChecklist(config);
    return new GeneratedBundle(files, installScript, checklist);
  }

  private shellRcPath(shell: ShellId): string {
    if (shell === 'fish') return '.config/fish/config.fish';
    return shell === 'zsh' ? '.zshrc' : '.bashrc';
  }

  private editorSettingsPath(editor: EditorId): string {
    if (editor === 'vscode') return '.dotfiles/vscode/settings.json';
    if (editor === 'neovim') return '.dotfiles/neovim/init.vim';
    return '.dotfiles/zed/settings.json';
  }

  private shellRcContent(shell: ShellId, editor: EditorId): string {
    const command = EDITOR_COMMAND[editor];
    if (shell === 'fish') {
      return [
        '# Shell configuration generated by Dev environment configurator.',
        `set -gx EDITOR ${command}`,
        'alias e "$EDITOR"',
        '',
      ].join('\n');
    }
    return [
      '# Shell configuration generated by Dev environment configurator.',
      `export EDITOR=${command}`,
      'alias e="$EDITOR"',
      '',
    ].join('\n');
  }

  private gitConfigContent(config: DeveloperConfig): string {
    return [
      '[user]',
      `\tname = ${config.git.name}`,
      `\temail = ${config.git.email}`,
      '[core]',
      `\teditor = ${EDITOR_COMMAND[config.editor]}`,
      '',
    ].join('\n');
  }

  private editorSettingsContent(editor: EditorId): string {
    if (editor === 'vscode') {
      return (
        JSON.stringify(
          { 'editor.formatOnSave': true, 'editor.tabSize': 2, 'files.eol': '\n' },
          null,
          2,
        ) + '\n'
      );
    }
    if (editor === 'neovim') {
      return [
        '" Editor configuration generated by Dev environment configurator.',
        'set tabstop=2',
        'set shiftwidth=2',
        'set expandtab',
        '',
      ].join('\n');
    }
    return JSON.stringify({ tab_size: 2, format_on_save: 'on' }, null, 2) + '\n';
  }

  private editorconfigContent(): string {
    return [
      'root = true',
      '',
      '[*]',
      'indent_style = space',
      'indent_size = 2',
      'end_of_line = lf',
      'charset = utf-8',
      'trim_trailing_whitespace = true',
      'insert_final_newline = true',
      '',
    ].join('\n');
  }

  private readmeContent(config: DeveloperConfig): string {
    return [
      '# Dotfiles',
      '',
      'A developer setup generated by Dev environment configurator.',
      '',
      `- shell: ${config.shell}`,
      `- git: ${config.git.name} <${config.git.email}>`,
      `- editor: ${config.editor}`,
      `- node: ${config.node.toString()}`,
      '',
      'Run `./install.sh` to place the files, then open `CHECKLIST.md`.',
      '',
    ].join('\n');
  }

  private checklistContent(config: DeveloperConfig): string {
    const items = this.buildChecklist(config).map((step) => `- [ ] ${step}`);
    return ['# Setup checklist', '', ...items, ''].join('\n');
  }

  private buildChecklist(config: DeveloperConfig): string[] {
    return [
      'Run `./install.sh` from this directory.',
      `Open a new terminal and run \`node -v\`; expect \`${config.node.toString()}\`.`,
      'Run `git config --list` and confirm your name and email.',
      `Open ${EDITOR_COMMAND[config.editor]} and confirm the settings are active.`,
      'Commit these files to a new git repository and push it.',
    ];
  }

  private buildFiles(config: DeveloperConfig): GeneratedFile[] {
    return [
      {
        path: this.shellRcPath(config.shell),
        content: this.shellRcContent(config.shell, config.editor),
      },
      { path: '.gitconfig', content: this.gitConfigContent(config) },
      { path: '.nvmrc', content: `${config.node.toString()}\n` },
      { path: '.editorconfig', content: this.editorconfigContent() },
      {
        path: this.editorSettingsPath(config.editor),
        content: this.editorSettingsContent(config.editor),
      },
      { path: '.dotfiles/CHECKLIST.md', content: this.checklistContent(config) },
      { path: '.dotfiles/README.md', content: this.readmeContent(config) },
    ];
  }

  private buildInstaller(config: DeveloperConfig, files: GeneratedFile[]): string {
    const blocks = files.map((file) => this.heredoc(file.path, file.content)).join('\n');
    const appendLine =
      config.shell === 'fish'
        ? 'fish_add_path "$HOME/.dotfiles/bin"'
        : 'export PATH="$HOME/.dotfiles/bin:$PATH"';
    const scaffold = `#!/usr/bin/env bash
# Generated by Dev environment configurator. Safe to run more than once.
set -euo pipefail

[ -n "$HOME" ] || { echo "HOME is not set" >&2; exit 1; }
HOME_DIR="$HOME"

# write_file <path>: write atomically through a temp file, then rename once.
write_file() {
  local path="$1"
  mkdir -p "$(dirname "$path")"
  local tmp
  tmp="$(mktemp "$path.XXXXXX")"
  cat > "$tmp"
  mv "$tmp" "$path"
}

# append_once <path> <line>: append a line only when it is not already there.
append_once() {
  local path="$1" line="$2"
  grep -qF "$line" "$path" 2>/dev/null || printf '%s\\n' "$line" >> "$path"
}
`;
    const tail = `
# Make the dotfiles bin directory available, once (idempotent).
mkdir -p "$HOME_DIR/.dotfiles/bin"
append_once "$HOME_DIR/${this.shellRcPath(config.shell)}" '${appendLine}'

echo "Done. Next: open $HOME_DIR/.dotfiles/CHECKLIST.md and work through it."
`;
    return scaffold + '\n' + blocks + tail;
  }

  private heredoc(path: string, content: string): string {
    return `write_file "$HOME_DIR/${path}" <<'DOTFILES_EOF'\n${content}DOTFILES_EOF`;
  }
}
